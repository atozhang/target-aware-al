"""Locks for the qualitative Wittig study of Fig 3E (`results/wittig_qualitative_study/`).

The split is regenerated from the released data (seconds); the 225 acquisitions are checked for
structure and chemical consistency here and regenerated by `scripts/wittig_qualitative_study.py`.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pandas as pd
import pytest

REPO = Path(__file__).resolve().parents[1]
STUDY = REPO / "results" / "wittig_qualitative_study"
_spec = importlib.util.spec_from_file_location("wittig_qualitative_study", REPO / "scripts" / "wittig_qualitative_study.py")
wqs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(wqs)

SEEDS = (0, 1, 2)
METHODS = {"EPIG", "BALD", "IndvNN"}
# badge: (group, record_id, acquisition rank in seed 1)
FIGURE_3E = {
    1: ("target", "CAS_R166", None), 2: ("target", "VP1994_T19_E043_C01", None),
    3: ("target", "VP1994_T19_E109_C01", None), 4: ("EPIG", "VP1994_T18_E019_C01", 3),
    5: ("EPIG", "CAS_R203", 1), 6: ("EPIG", "VP1994_T21_E042_C01", 6),
    7: ("BALD", "VP1994_T13_E055_C01", 17), 8: ("BALD", "VP1994_T15_E086_C01", 7),
    9: ("BALD", "VP1994_T15_E073_C01", 16), 10: ("IndvNN", "VP1994_T19_E038_C01", 25),
    11: ("IndvNN", "VP1994_T19_E105_C01", 3), 12: ("IndvNN", "VP1994_T19_E044_C01", 8),
}


@pytest.fixture(scope="module")
def reactions() -> pd.DataFrame:
    return wqs.load_reactions()


@pytest.fixture(scope="module")
def membership() -> pd.DataFrame:
    return pd.read_csv(STUDY / "split_membership.csv", dtype={"umap_1": str, "umap_2": str})


@pytest.fixture(scope="module")
def acquisitions() -> pd.DataFrame:
    return pd.read_csv(STUDY / "acquisitions.csv", keep_default_na=False)


@pytest.fixture(scope="module")
def figure() -> pd.DataFrame:
    return pd.read_csv(STUDY / "figure_3e_reactions.csv", keep_default_na=False)


def test_membership_follows_the_released_dataset_order(membership, reactions):
    assert membership["record_id"].tolist() == reactions["record_id"].tolist()
    assert membership["source"].tolist() == reactions["source"].tolist()


def test_split_sizes_and_shared_target(membership):
    targets = []
    for seed in SEEDS:
        role = membership[f"role_seed{seed}"]
        assert role.value_counts().to_dict() == {"candidate": 879, "target": 63, "initial": 25}
        targets.append(set(membership.loc[role.eq("target"), "record_id"]))
    assert targets[0] == targets[1] == targets[2]


def test_split_regenerates_from_the_released_data(membership, reactions):
    target, _, initial = wqs.study_split(reactions, membership[["umap_1", "umap_2"]].astype(float).to_numpy())
    regenerated = wqs.membership_table(reactions, target, initial)
    assert regenerated.equals(membership[regenerated.columns])


def test_acquisitions_are_ordered_unique_candidates(acquisitions, membership):
    assert len(acquisitions) == 225 and set(acquisitions["study_id"]) == {wqs.STUDY_ID}
    runs = acquisitions.groupby(["seed", "method"])
    assert set(runs.groups) == {(s, m) for s in SEEDS for m in METHODS}
    role = membership.set_index("record_id")
    for (seed, _), run in runs:
        assert run["acquisition_rank"].tolist() == list(range(1, 26))
        assert run["record_id"].is_unique
        assert (role.loc[run["record_id"], f"role_seed{seed}"] == "candidate").all()


@pytest.mark.parametrize("name", ["acquisitions.csv", "figure_3e_reactions.csv"])
def test_reaction_chemistry_is_consistent_with_the_dataset(name, reactions):
    table = pd.read_csv(STUDY / name, keep_default_na=False)
    data = reactions.set_index("record_id")
    assert (table["source"].to_numpy() == data.loc[table["record_id"], "source"].to_numpy()).all()
    assert (table["z_selectivity_percent"].astype(float).to_numpy()
            == data.loc[table["record_id"], "z_selectivity_percent"].to_numpy()).all()
    for r in table.itertuples():
        z = float(r.z_selectivity_percent)
        e_part, z_part = map(float, r.e_z_ratio.split(":"))
        assert z_part == pytest.approx(z) and e_part + z_part == pytest.approx(100)
        assert r.major_isomer == ("Z" if z > 50 else "E" if z < 50 else "1:1")
        product = {"Z": r.z_alkene_smiles, "E": r.e_alkene_smiles,
                   "1:1": f"{r.z_alkene_smiles}.{r.e_alkene_smiles}"}[r.major_isomer]
        assert product and r.product_smiles == product
        assert r.reaction_smiles == f"{r.carbonyl_smiles}.{r.ylide_smiles}>>{r.product_smiles}"
        assert r.product_provenance


def test_figure_3e_reactions_trace_to_the_study(figure, acquisitions, membership):
    got = {int(r.badge): (r.group, r.record_id, int(r.acquisition_rank) if r.acquisition_rank != "" else None)
           for r in figure.itertuples()}
    assert got == FIGURE_3E
    assert set(figure["seed"]) == {1}
    role = membership.set_index("record_id")["role_seed1"]
    seed1 = acquisitions[acquisitions["seed"].eq(1)]
    chemistry = [c for c in figure.columns if c not in ("badge", "group", "seed", "acquisition_rank")]
    for r in figure.itertuples():
        if r.group == "target":
            assert role[r.record_id] == "target"
            continue
        hit = seed1[seed1["method"].eq(r.group) & seed1["record_id"].eq(r.record_id)]
        assert len(hit) == 1 and int(hit["acquisition_rank"].iloc[0]) == int(r.acquisition_rank)
        assert hit[chemistry].iloc[0].astype(str).tolist() == figure.loc[r.Index, chemistry].astype(str).tolist()
